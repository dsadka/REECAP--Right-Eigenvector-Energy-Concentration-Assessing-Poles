% IEEE-style figure defaults: Times New Roman, tex text, thin axes.
% tick_interpreter = 'tex' (default) or 'latex' (used by the sensitivity figures).
function set_sp_figure_settings(font_size, tick_interpreter)

if nargin < 2
    tick_interpreter = 'tex';
end
reset(groot);
set(groot, 'defaultAxesFontName', 'Times New Roman', ...
           'defaultTextFontName', 'Times New Roman', ...
           'defaultLegendFontName', 'Times New Roman', ...
           'defaultAxesFontSize', font_size, ...
           'defaultTextInterpreter', 'tex', ...
           'defaultAxesTickLabelInterpreter', tick_interpreter, ...
           'defaultLegendInterpreter', 'tex', ...
           'defaultLineLineWidth', 1.1, ...
           'defaultLineMarkerSize', 2.5, ...
           'defaultAxesLineWidth', 0.6);

end
